total = 0
for path in FILES:
    try:
        with io.open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        print("  (skip, not found) " + path)
        continue
    n = 0
    for bad, good in REPLACEMENTS:
        c = text.count(bad)
        if c:
            text = text.replace(bad, good)
            n += c
    if any(k in path for k in ("question_bank", "traits_dropped", "indicators_classified", "indicators_unique")):
        for bad, good in QB_REGEX:
            pat = re.escape(bad) + "(?!" + AR + ")"
            new, c = re.subn(pat, good, text)
            text = new; n += c
        for bad, good in QB_PLAIN:
            c = text.count(bad)
            if c:
                text = text.replace(bad, good); n += c
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(text)
    total += n
    print("  fixed %4d  %s" % (n, path))

print("TOTAL replacements: %d" % total)
